"""Generate offline demo data from the same initial bundle used by the server."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT = ROOT / "data/default"


def build(root=ROOT):
    root = Path(root)
    default = root / "data/default"
    assets = root / "public/js"
    names = (
        "schedule_numerator",
        "schedule_denominator",
        "shelter_numerator",
        "shelter_denominator",
    )
    data = {
        name: json.loads((default / (name + ".json")).read_text(encoding="utf-8"))
        for name in names
    }
    calendar = json.loads((default / "calendar.json").read_text(encoding="utf-8"))
    for name, variable, value in (
        ("demo_data.js", "LYCEUM_DEMO_DATA", data),
        (
            "demo_calendar.js",
            "LYCEUM_DEMO_CALENDAR",
            {
                key: calendar.get(key, [])
                for key in ("ranges", "openEndedRanges", "daysOff")
            },
        ),
    ):
        payload = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
        (assets / name).write_text(
            "// Generated by tools/build_demo.py; edit data/default instead.\nwindow."
            + variable
            + "="
            + payload
            + ";\n",
            encoding="utf-8",
        )


if __name__ == "__main__":
    build()
